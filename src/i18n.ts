const dictionaries = { en, "zh-CN": zh } satisfies Record<Locale, Record<TranslationKey, string>>;

export type { TranslationKey };
export type Translator = (key: TranslationKey) => string;

export function resolveLocale(language: LanguageSetting, systemLanguage?: string): Locale {
  if (language === "en" || language === "zh-CN") return language;
  return systemLanguage?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function createTranslator(locale: Locale): Translator {
  return (key) => dictionaries[locale][key] ?? dictionaries.en[key];
}
